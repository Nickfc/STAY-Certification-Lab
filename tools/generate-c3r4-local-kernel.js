#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const OUTPUT = path.resolve(__dirname,
  '../cores/chronobiology/c3r4/local-ring-kernel.js');

function edgeBlock(left, right) {
  return `
  phase = (phase${right} - phase${left}) >>> 0;
  index = phase >>> 20;
  fraction = phase & 0xf_ffff;
  current = sinValues[index];
  scaled = sinDeltas[index] * fraction;
  sine = current + (scaled < 0
    ? -(((-scaled + 524_288) * Q20_RECIPROCAL) | 0)
    : (((scaled + 524_288) * Q20_RECIPROCAL) | 0));
  response = sine < 0 ? -((-sine + 4) >>> 3) : ((sine + 4) >>> 3);
  sum${left} += response;
  sum${right} -= response;
`;
}

function generate() {
  const blocks = [];
  const phaseSlots = [];
  const sumSlots = [];
  const sumStores = [];
  for (let left = 0; left < 64; left += 1) {
    phaseSlots.push(`  const phase${left} = phases[${left}];`);
    sumSlots.push(`  let sum${left} = sums[${left}];`);
    sumStores.push(`  sums[${left}] = sum${left};`);
    blocks.push(edgeBlock(left, (left + 1) & 63));
    blocks.push(edgeBlock(left, (left + 2) & 63));
  }
  return `'use strict';

/*
 * Generated by tools/generate-c3r4-local-kernel.js. The C3RC.4 compiled-plan
 * admission fence proves this exact 64-node ±1/±2 ring before this kernel is
 * called. Static endpoints remove Ignition loop and dynamic-index work; all
 * fixed-point arithmetic is the frozen C3RC.3 operation sequence.
 */
const Q20_RECIPROCAL = 9.5367431640625e-7;

function accumulateLocalRing(phases, sums, sinValues, sinDeltas) {
${phaseSlots.join('\n')}
${sumSlots.join('\n')}
  let phase;
  let index;
  let fraction;
  let current;
  let scaled;
  let sine;
  let response;
${blocks.join('')}
${sumStores.join('\n')}
}

module.exports = { accumulateLocalRing };
`;
}

if (require.main === module) {
  fs.writeFileSync(OUTPUT, generate(), 'utf8');
}

module.exports = { OUTPUT, generate };
