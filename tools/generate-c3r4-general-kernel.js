#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const OUTPUT = path.resolve(__dirname,
  '../cores/chronobiology/c3r4/general-edge-kernel.js');

function edgeBlock(edgeId) {
  return `
  units = generalUnits[${edgeId}];
  left = units & 63;
  right = units >>> 6;
  phase = (phases[right] - phases[left]) >>> 0;
  index = phase >>> 20;
  fraction = phase & 0xf_ffff;
  current = sinValues[index];
  scaled = sinDeltas[index] * fraction;
  sine = current + (scaled < 0
    ? -(((-scaled + 524_288) * Q20_RECIPROCAL) | 0)
    : (((scaled + 524_288) * Q20_RECIPROCAL) | 0));
  response = 0;
  if (sine !== 0) {
    sineMagnitude = sine < 0 ? -sine : sine;
    scaledProduct = sineMagnitude * generalWeightScale[${edgeId}];
    productFloor = scaledProduct | 0;
    productFraction = scaledProduct - productFloor;
    if (productFraction < 0.5 - ADAPTIVE_ROUNDING_GUARD
      || productFraction > 0.5 + ADAPTIVE_ROUNDING_GUARD) {
      magnitude = productFloor + (productFraction >= 0.5 ? 1 : 0);
    } else {
      sineHigh = sineMagnitude >>> 15;
      sineLow = sineMagnitude & 0x7fff;
      weightHigh = generalWeightHigh[${edgeId}];
      weightLow = generalWeightLow[${edgeId}];
      exactHigh = sineHigh * weightHigh;
      exactLow = (sineHigh * weightLow + sineLow * weightHigh) * Q30_SPLIT
        + sineLow * weightLow;
      magnitude = exactHigh
        + Math.floor((exactLow + 536_870_912) * Q30_RECIPROCAL);
    }
    response = sine < 0 ? -magnitude : magnitude;
  }
  sums[left] += response;
  sums[right] -= response;
`;
}

function generate() {
  const blocks = [];
  for (let edgeId = 0; edgeId < 64; edgeId += 1) {
    blocks.push(edgeBlock(edgeId));
  }
  return `'use strict';

/*
 * Generated by tools/generate-c3r4-general-kernel.js. C3RC.4 admits exactly
 * 64 founder long-range edges before this unrolled kernel is callable. The
 * arithmetic and operation order are the frozen C3RC.3 contract.
 */
const Q30_SPLIT = 32_768;
const Q20_RECIPROCAL = 9.5367431640625e-7;
const Q30_RECIPROCAL = 9.313225746154785e-10;
const ADAPTIVE_ROUNDING_GUARD = 0.00001;

function accumulateGeneralEdges(phases, sums, generalUnits,
  generalWeightHigh, generalWeightLow, generalWeightScale,
  sinValues, sinDeltas) {
  let units;
  let left;
  let right;
  let phase;
  let index;
  let fraction;
  let current;
  let scaled;
  let sine;
  let response;
  let sineMagnitude;
  let scaledProduct;
  let productFloor;
  let productFraction;
  let magnitude;
  let sineHigh;
  let sineLow;
  let weightHigh;
  let weightLow;
  let exactHigh;
  let exactLow;
${blocks.join('')}
}

module.exports = { accumulateGeneralEdges };
`;
}

if (require.main === module) {
  fs.writeFileSync(OUTPUT, generate(), 'utf8');
}

module.exports = { OUTPUT, generate };
